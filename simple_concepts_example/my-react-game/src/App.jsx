import React, { useState } from 'react';
import Header from './Header';
import GameCanvas from './GameCanvas';

export default function App() {
  // 1. CREATE STATE
  // We declare a variable called 'count' starting at 0.
  // 'setCount' is the special function we use to change that number.
  const [count, setCount] = useState(0);

  // 2. THE EVENT HANDLER
  // This function runs when the button gets clicked.
  function handleClick() {
    // We call the dispatcher function and pass in the new number.
    setCount(count + 1);
  }

  // 3. THE UI BLUEPRINT (JSX)
  // We tell React: "I want a screen with a heading and a button."
  return (
    <div>
      <Header />
      {/* Curly braces {} open up a portal to show our 'count' variable */}
      <h1>The count is: {count}</h1>
      
      {/* We tell the button to run 'handleClick' when it is clicked */}
      <button onClick={handleClick}>
        Click Me!
      </button>
      <GameCanvas />
    </div>
  );
}

